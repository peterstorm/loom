/**
 * Guarded Skill Machine integrity (ADR-0076, issue #183).
 *
 * A machine is the gate on its own agent, so a gated agent that could rewrite,
 * add or delete a definition could weaken its own gate. The machines directory
 * is fenced from subagent writes only by guards that read shell strings, and an
 * agent that plants a file some ordinary tool later executes (a repository's
 * core.fsmonitor setting, a git hook, a package script) passes every such fence. So
 * the definitions Loom ships are pinned: the SHA-256 of each shipped machine's
 * exact bytes is compiled into the engine (`machine-pins.ts`, generated by
 * `npm run pin-machines`), and a definition is admitted only when its bytes
 * match its pin.
 *
 * The pin set, not the directory listing, says which agent types are gated:
 * - a pinned agent whose file is gone is refused (deleting a machine must not
 *   ungate its agent);
 * - a file with no pin is refused (an added machine is not Loom's);
 * - a file whose digest differs from its pin is refused.
 * The loader maps every refusal to an invalid machine, which binds and fails
 * the gate closed (`machines/README.md`), so tampering can only make the gate
 * stricter, never weaker.
 *
 * A directory the operator points `LOOM_MACHINES_DIR` at is the operator's own
 * (`operator-directory`): the hook's environment comes from the harness, not
 * from the agent, and tests point it at fixture machines. It is admitted as it
 * stands.
 *
 * Residual (stated in ADR-0076): code running as the user can rewrite a machine
 * AND its pin in engine source together. Pinning raises a one-file data write
 * to a coordinated change of shipped code; only OS isolation closes the rest.
 *
 * Pure: no I/O. The shell reads the bytes and supplies the trust.
 */

import { artifactDigestOfBytes } from "./digest";
import {
  failure,
  parseArtifactDigest,
  success,
  type ArtifactDigest,
  type DomainResult,
} from "./orchestration-contract/identity";
import { parseAgentType, type AgentType } from "../machine/evidence";

/** The pinned SHA-256 of each shipped machine, keyed by the agent type it gates. */
export type MachinePins = ReadonlyMap<AgentType, ArtifactDigest>;

/** How far a machines directory is trusted. */
export type MachineTrust =
  | Readonly<{ kind: "pinned"; pins: MachinePins }>
  | Readonly<{ kind: "operator-directory" }>;

/** Where machine definitions are read from, and how far they are trusted. */
export type MachineSource = Readonly<{ directory: string; trust: MachineTrust }>;

/** Why a machine definition was refused. */
export type MachineRefusal =
  | Readonly<{ kind: "pinned-machine-missing"; agentType: AgentType; pinned: ArtifactDigest }>
  | Readonly<{ kind: "unpinned-machine"; agentType: AgentType; actual: ArtifactDigest }>
  | Readonly<{ kind: "digest-mismatch"; agentType: AgentType; pinned: ArtifactDigest; actual: ArtifactDigest }>;

/**
 * The decision for one agent type's definition. `admitted` carries the exact
 * bytes the decision judged, so the caller parses what was admitted and never
 * re-reads the file.
 */
export type MachineAdmission =
  | Readonly<{ kind: "ungated" }>
  | Readonly<{ kind: "admitted"; bytes: Uint8Array }>
  | Readonly<{ kind: "refused"; refusal: MachineRefusal }>;

/**
 * Admit, refuse or ungate one agent type's definition. `bytes` is null when
 * the definition file does not exist. Total over every trust and presence.
 */
export function admitMachineDefinition(
  trust: MachineTrust,
  agentType: AgentType,
  bytes: Uint8Array | null,
): MachineAdmission {
  if (trust.kind === "operator-directory") {
    return Object.freeze(bytes === null ? { kind: "ungated" } : { kind: "admitted", bytes });
  }
  const pinned = trust.pins.get(agentType);
  if (bytes === null) {
    return pinned === undefined
      ? Object.freeze({ kind: "ungated" })
      : refused({ kind: "pinned-machine-missing", agentType, pinned });
  }
  const actual = artifactDigestOfBytes(bytes);
  if (pinned === undefined) return refused({ kind: "unpinned-machine", agentType, actual });
  if (pinned !== actual) return refused({ kind: "digest-mismatch", agentType, pinned, actual });
  return Object.freeze({ kind: "admitted", bytes });
}

const refused = (refusal: MachineRefusal): MachineAdmission =>
  Object.freeze({ kind: "refused", refusal: Object.freeze(refusal) });

/** The command that re-pins the shipped machines after an intended change. */
export const PIN_MACHINES_COMMAND = "cd engine && npm run pin-machines";

/** One refusal as the gate reports it: what was wrong, and how to fix an intended change. */
export function renderMachineRefusal(refusal: MachineRefusal): string {
  const repin = `if the change to machines/ was intended, run \`${PIN_MACHINES_COMMAND}\` and commit the pins; ` +
    "otherwise the shipped definition was altered";
  switch (refusal.kind) {
    case "pinned-machine-missing":
      return `the shipped machine for ${refusal.agentType} is pinned (sha256 ${refusal.pinned}) but its file is missing; ${repin}`;
    case "unpinned-machine":
      return `no shipped machine is pinned for ${refusal.agentType} (file sha256 ${refusal.actual}); ${repin}`;
    case "digest-mismatch":
      return `machine definition for ${refusal.agentType} has sha256 ${refusal.actual}, but the engine pins ${refusal.pinned}; ${repin}`;
    default:
      return assertNever(refusal);
  }
}

const assertNever = (value: never): never => {
  throw new Error(`unreachable machine refusal: ${JSON.stringify(value)}`);
};

/** One pin as the generated module records it. */
export type MachinePinEntry = Readonly<{ agentType: AgentType; digest: ArtifactDigest }>;

/** Parse the generated pin record: every key an agent type, every value a SHA-256. */
export function parseMachinePins(raw: Readonly<Record<string, string>>): DomainResult<MachinePins, string> {
  const pins = new Map<AgentType, ArtifactDigest>();
  for (const [key, value] of Object.entries(raw)) {
    const agentType = parseAgentType(key);
    if (agentType === null) return failure(`machine pin key ${JSON.stringify(key)} is not an agent type`);
    const digest = parseArtifactDigest(value);
    if (!digest.ok) return failure(`machine pin for ${key} is not a SHA-256 digest: ${digest.error.message}`);
    pins.set(agentType, digest.value);
  }
  return success(pins);
}

/**
 * The generated pin module's exact text. Entries are sorted by agent type, so
 * the same machines always render the same bytes and the drift test can
 * compare the file on disk with what `npm run pin-machines` would write.
 */
export function renderMachinePinsModule(entries: readonly MachinePinEntry[]): string {
  const sorted = [...entries].sort((a, b) => (a.agentType < b.agentType ? -1 : a.agentType > b.agentType ? 1 : 0));
  const lines = sorted.map(({ agentType, digest }) => `  ${JSON.stringify(agentType)}: ${JSON.stringify(digest)},`);
  return [
    "/**",
    " * @generated by `npm run pin-machines` (engine/scripts/pin-machines.ts). Do not edit by hand.",
    " *",
    " * The SHA-256 of every shipped Guarded Skill Machine definition",
    " * (`machines/<agent-type>.machine.json`), keyed by agent type. The loader",
    " * admits a shipped definition only when its bytes match its pin (ADR-0076).",
    " */",
    "export const SHIPPED_MACHINE_PINS: Readonly<Record<string, string>> = Object.freeze({",
    ...lines,
    "});",
    "",
  ].join("\n");
}
