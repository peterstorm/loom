/**
 * The skeleton values a TaskGraph and its Tasks persist (AD-4): the export
 * binding stamp (`TaskGraph.export_bindings`), the engine-written skeleton
 * records (`TaskGraph.skeletons`) and each Task's recorded outcomes
 * (`Task.skeleton_outcomes`), with every type they reference.
 *
 * A leaf: it imports nothing from `engine/src/types.ts` (and nothing that
 * does), so `types.ts` can import these to declare the G2 fields on the
 * canonical `TaskGraph` and `Task` without an import cycle. `./types.ts`
 * re-exports every name here, so skeleton consumers keep importing from it.
 * Declarations only, no logic.
 */

import type { NonEmpty } from "../orchestration-contract/identity";

declare const IDENTIFIER: unique symbol;

/**
 * An export name or alias that matches `^[A-Za-z_][A-Za-z0-9_]*$` and is no
 * reserved word of TypeScript or Java (one fixed list). Branded:
 * `bindings.ts`'s `parseIdentifier` is its only constructor, and
 * `parseExportBindings` mints every bound name and alias through it, so
 * generated bytes only ever splice validated identifiers.
 */
export type Identifier = string & Readonly<{ [IDENTIFIER]: true }>;

declare const CONTRACT_ID: unique symbol;

/**
 * An acceptance contract id, `CT-<digits>`. Branded: `bindings.ts`'s
 * `parseContractId` is its only constructor, and the binding grammar mints
 * every contract it reads through it. A ContractId is a string on the wire
 * and is assignable wherever a contract id is still typed `string`.
 */
export type ContractId = string & Readonly<{ [CONTRACT_ID]: true }>;

/** One bound export: the exported name and the frozen function-type alias
 *  that types it. */
export type BoundExport = Readonly<{ name: Identifier; alias: Identifier }>;

/** One `` - `path` — CT-n: name: Alias, … `` line: the exports a file
 *  provides, all typed by one contract's frozen types file, in plan order.
 *  `contract` is a `ContractId`'s text: the binding grammar mints it, but the
 *  field stays `string` because the State File wire and the frozen CT-1
 *  acceptance tests construct bindings from plain strings. */
export type ExportBinding = Readonly<{
  path: string;
  contract: string;
  exports: NonEmpty<BoundExport>;
}>;

export type SkeletonLanguage = "typescript" | "java";

/** Why a path is no skeleton target. */
export type UnsupportedReason =
  | "other-extension"
  | "java-outside-main-root"
  | "java-invalid-name"
  | "jvm-non-java";

export type SkeletonOrigin = "spawn" | "contract-stub" | "revision";

/** Exactly one per non-test file_list path. */
export type SkeletonOutcome =
  | Readonly<{ kind: "skeleton-written"; origin: SkeletonOrigin }>
  | Readonly<{ kind: "no-bound-exports" }>
  | Readonly<{ kind: "contract-has-no-types-file" }>
  | Readonly<{ kind: "unsupported-language"; reason: UnsupportedReason }>
  | Readonly<{ kind: "exists-not-skeletonized" }>;

export type PathSkeletonOutcome = Readonly<{ path: string; outcome: SkeletonOutcome }>;

/** One engine-written skeleton: the digest of the bytes the engine wrote and
 *  of the types file they came from, and whether a Contract Revision left it
 *  stale because it had been modified. */
export type SkeletonRecord = Readonly<{
  path: string;
  contract: string;
  language: SkeletonLanguage;
  origin: SkeletonOrigin;
  engineSha256: string;
  typesSha256: string;
  stale: null | Readonly<{ revision: number }>;
}>;
