/**
 * The one supported-language predicate (AD-15, INV-6 owner) and the only
 * constructor of the branded `SkeletonTarget`.
 *
 * A path is a TypeScript target when its basename ends in `.ts`, `.tsx`,
 * `.mts` or `.cts` and it is no `.d.ts`/`.d.mts`/`.d.cts` declaration file.
 * It is a Java target when it is a `.java` file under a `src/main/java/` root
 * (the first one, so a module prefix such as `billing/` is allowed): the
 * package is the path after that root (null for the default package) and the
 * class the basename, each segment a Java identifier and no reserved word, so
 * generated bytes only ever splice valid names. Everything else is
 * unsupported, with one reason: Kotlin and Scala are `jvm-non-java`, any
 * other `.java` path `java-outside-main-root` or `java-invalid-name`, and
 * the rest `other-extension`. An extension is the basename's text from its
 * last dot, when that dot is not its first character.
 *
 * Every consumer works from the parsed value and never re-decides it. Pure.
 */

import type {
  JavaSkeletonTarget,
  SkeletonLanguageOfFn,
  TsSkeletonTarget,
  UnsupportedReason,
  UnsupportedTarget,
} from "./types";

const TYPESCRIPT_EXTENSIONS: readonly string[] = [".ts", ".tsx", ".mts", ".cts"];
const DECLARATION_FILE = /\.d\.[mc]?ts$/;
const JVM_NON_JAVA_EXTENSIONS: readonly string[] = [".kt", ".kts", ".scala"];
const JAVA_ROOT: readonly string[] = ["src", "main", "java"];
const JAVA_IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/**
 * Java's reserved keywords, contextual `_`, and the literals no identifier
 * may spell: the one owner of Java's keyword core. The binding grammar's
 * reserved words (`parseIdentifier`) are built from it.
 */
export const JAVA_RESERVED_WORDS: ReadonlySet<string> = new Set([
  "_", "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char", "class", "const",
  "continue", "default", "do", "double", "else", "enum", "extends", "false", "final", "finally",
  "float", "for", "goto", "if", "implements", "import", "instanceof", "int", "interface", "long",
  "native", "new", "null", "package", "private", "protected", "public", "return", "short", "static",
  "strictfp", "super", "switch", "synchronized", "this", "throw", "throws", "transient", "true",
  "try", "void", "volatile", "while",
]);

const unsupported = (path: string, reason: UnsupportedReason): UnsupportedTarget =>
  Object.freeze({ kind: "unsupported", path, reason });

const isJavaName = (name: string): boolean => JAVA_IDENTIFIER.test(name) && !JAVA_RESERVED_WORDS.has(name);

/** The index of the first `src/main/java` segment run, or -1. */
const javaRootIndex = (segments: readonly string[]): number =>
  segments.findIndex((_, at) => JAVA_ROOT.every((part, offset) => segments[at + offset] === part));

function javaTarget(path: string, segments: readonly string[], className: string): JavaSkeletonTarget | UnsupportedTarget {
  const root = javaRootIndex(segments);
  if (root < 0) return unsupported(path, "java-outside-main-root");
  const packageSegments = segments.slice(root + JAVA_ROOT.length, -1);
  if (![...packageSegments, className].every(isJavaName)) return unsupported(path, "java-invalid-name");
  // The brand's one minting point for Java: every name was just proved valid.
  return Object.freeze({
    kind: "supported",
    language: "java",
    path,
    package: packageSegments.length === 0 ? null : packageSegments.join("."),
    className,
  }) as JavaSkeletonTarget;
}

export const skeletonLanguageOf: SkeletonLanguageOfFn = (path) => {
  const segments = path.split("/");
  const basename = segments[segments.length - 1]!;
  const dot = basename.lastIndexOf(".");
  const extension = dot > 0 ? basename.slice(dot) : "";
  if (TYPESCRIPT_EXTENSIONS.includes(extension) && !DECLARATION_FILE.test(basename)) {
    // The brand's one minting point for TypeScript.
    return Object.freeze({ kind: "supported", language: "typescript", path }) as TsSkeletonTarget;
  }
  if (extension === ".java") return javaTarget(path, segments, basename.slice(0, dot));
  return unsupported(path, JVM_NON_JAVA_EXTENSIONS.includes(extension) ? "jvm-non-java" : "other-extension");
};
