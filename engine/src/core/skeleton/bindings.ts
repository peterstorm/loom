function renderMalformedReason(reason: MalformedEntryReason): string {
  return match(reason)
    .with("not-a-binding-line", () => "is not '- `path` — CT-n: name: Alias, …'")
    .with("missing-contract", () => "names no 'CT-n:' contract after the path")
    .with("missing-name", () => "has an entry missing its export name ('name: Alias')")
    .with("missing-alias", () => "has an entry missing its alias ('name: Alias')")
    .with("empty-exports", () => "binds no exports after its contract")
    .with("invalid-identifier", () => "has a name or alias that is not an identifier ([A-Za-z_][A-Za-z0-9_]*)")
    .with("reserved-word", () => "has a name or alias that is a reserved word of TypeScript or Java")
    .exhaustive();
}

/** One refusal as the operator message plan validation reports: it names the
 *  file and the reason. */
export function renderBindingProblem(problem: BindingProblem): string {
  return match(problem)
    .with({ kind: "unsafe-path" }, ({ path }) =>
      `'${path}' is not a repository-relative path — a bound path must stay inside the repository`)
    .with({ kind: "frozen-path" }, ({ path, contract }) =>
      `'${path}' is a frozen path of ${contract} — the types file and acceptance tests are never bound`)
    .with({ kind: "malformed-entry" }, ({ path, line, reason }) =>
      `${path === null ? "a binding line" : `the binding of '${path}'`} '${line}' ${renderMalformedReason(reason)}`)
    .with({ kind: "duplicate-name" }, ({ path, name }) => `'${path}' binds the export name '${name}' twice`)
    .with({ kind: "name-collides-with-alias" }, ({ path, name }) =>
      `'${path}' binds the export name '${name}', which is also an alias on its line — a TypeScript skeleton cannot import a type and declare a value of one name; rename the export`)
    .with({ kind: "alias-collides-with-class" }, ({ path, alias }) =>
      `'${path}' binds the alias '${alias}', the file's own class name — the Java skeleton's import of that alias would clash with the class it declares; rename the file or the alias`)
    .with({ kind: "duplicate-path" }, ({ path, contract }) =>
      `'${path}' is bound on two ${contract} lines — list every export of a file on one line`)
    .with({ kind: "multi-contract" }, ({ path, contracts }) =>
      `'${path}' is bound by ${contracts.join(" and ")} — one file binds to one contract's types file`)
    .with({ kind: "unknown-contract" }, ({ path, contract }) => `'${path}' is bound to ${contract}, which the plan does not declare`)
    .with({ kind: "contract-without-types" }, ({ path, contract }) =>
      `'${path}' is bound to ${contract}, which declares '**Types file:** none' — there is nothing to bind to`)
    .with({ kind: "bound-on-contract-task" }, ({ path, contract, task }) =>
      `'${path}' is in the file_list of ${task}, ${contract}'s contract task — the engine writes the bound skeleton; list it on the Task that implements it`)
    .with({ kind: "unheld-path" }, ({ path }) =>
      `'${path}' is in no implementing task's file_list — decompose must emit the task that implements it`)
    .with({ kind: "holder-not-after-contract" }, ({ path, task, contractTask }) =>
      `'${path}' is implemented by ${task}, which does not depend on contract task ${contractTask}, directly or transitively`)
    .with({ kind: "bound-on-waived-task" }, ({ path, task, reason }) =>
      `'${path}' is implemented by ${task}, whose regression waiver is '${reason}' — a bound path is production code`)
    .exhaustive();
}

/**
 * Whether the bindings population stamped still agree with the recorded
 * plan's: equal exactly when they render to the same lines in the same order.
 * On drift, names each line the plan adds and each the stamp holds that the
 * plan no longer does.
 */
export function bindingStampAgreement(plan: readonly ExportBinding[], stamp: readonly ExportBinding[]): DomainResult<null, string> {
  const planLines = plan.map(renderExportBinding);
  const stampLines = stamp.map(renderExportBinding);
  if (planLines.length === stampLines.length && planLines.every((line, index) => line === stampLines[index])) {
    return { ok: true, value: null };
  }
  const added = planLines.filter((line) => !stampLines.includes(line));
  const dropped = stampLines.filter((line) => !planLines.includes(line));
  const details = [
    ...added.map((line) => `the plan binds ${line}`),
    ...dropped.map((line) => `the stamp binds ${line}`),
  ];
  return {
    ok: false,
    error: `the plan's export bindings drifted from the TaskGraph stamp: ${
      details.length === 0 ? "the same bindings in a different order" : details.join("; ")
    } — re-populate the TaskGraph`,
  };
}
