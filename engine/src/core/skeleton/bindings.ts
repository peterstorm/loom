/** Regression waivers that say the Task changes no production code — a bound
 *  path on such a Task contradicts itself. */
const NON_PRODUCTION_WAIVERS: ReadonlySet<RegressionWaiverReason> = new Set(["documentation-only", "generated-artifact"]);

/** A declared contract with its frozen paths and its contract Task (null when
 *  no single writer resolves; contract binding reports that). */
type DeclaredContract = Readonly<{ id: string; hasTypes: boolean; frozen: readonly string[]; contractTask: string | null }>;

function declaredContracts(contracts: readonly PlanContract[], tasks: readonly BindingTaskView[]): readonly DeclaredContract[] {
  return contracts.flatMap(({ id, declaration }) => {
    if (declaration.kind === "malformed") return [];
    const frozen = frozenPaths(declaration);
    const writer = contractWriter(frozen, tasks);
    return [{ id, hasTypes: declaration.types.kind === "file", frozen, contractTask: writer.ok ? writer.value : null }];
  });
}

/** Every graph-shape refusal of one well-formed binding, in a fixed order. */
function bindingProblems(
  binding: ExportBinding,
  contracts: readonly PlanContract[],
  declared: readonly DeclaredContract[],
  tasks: readonly BindingTaskView[],
): readonly BindingProblem[] {
  const { path } = binding;
  const unsafe: readonly BindingProblem[] = isRepoRelativePlanPath(path) ? [] : [{ kind: "unsafe-path", path }];
  const frozen = declared
    .filter(({ frozen: paths }) => paths.some((frozenPath) => samePlanPath(frozenPath, path)))
    .map(({ id }): BindingProblem => ({ kind: "frozen-path", path, contract: id }));

  const own = declared.find(({ id }) => id === binding.contract) ?? null;
  const contractProblems: readonly BindingProblem[] = own !== null
    ? (own.hasTypes ? [] : [{ kind: "contract-without-types", path, contract: own.id }])
    // A malformed contract is reported by contract validation, not here.
    : contracts.some(({ id }) => id === binding.contract) ? [] : [{ kind: "unknown-contract", path, contract: binding.contract }];

  const contractTask = own?.contractTask ?? null;
  const listing = tasks.filter(({ file_list }) => file_list.some((file) => samePlanPath(file, path)));
  const onContractTask: readonly BindingProblem[] = own !== null && contractTask !== null && listing.some(({ id }) => id === contractTask)
    ? [{ kind: "bound-on-contract-task", path, contract: own.id, task: contractTask }]
    : [];
  const holders = listing.filter(({ id }) => id !== contractTask);
  const byId = new Map(tasks.map((task) => [task.id, task] as const));
  const holderProblems = holders.flatMap((holder): BindingProblem[] => [
    ...(contractTask === null || dependsOnAny(holder.depends_on, new Set([contractTask]), (taskId) => byId.get(taskId)?.depends_on ?? [])
      ? []
      : [{ kind: "holder-not-after-contract", path, task: holder.id, contractTask } as const]),
    ...(holder.regressionWaiver !== null && NON_PRODUCTION_WAIVERS.has(holder.regressionWaiver)
      ? [{ kind: "bound-on-waived-task", path, task: holder.id, reason: holder.regressionWaiver } as const]
      : []),
  ]);

  return [
    ...unsafe,
    ...frozen,
    ...contractProblems,
    ...onContractTask,
    ...(holders.length === 0 ? [{ kind: "unheld-path", path } as const] : []),
    ...holderProblems,
  ];
}

export const validateExportBindings: ValidateExportBindingsFn = (declaration, contracts, tasks) => {
  const declared = declaredContracts(contracts, tasks);
  return [
    ...declaration.problems,
    ...declaration.bindings.flatMap((binding) => bindingProblems(binding, contracts, declared, tasks)),
  ];
};

