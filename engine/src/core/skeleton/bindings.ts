// ---------------------------------------------------------------------------
// Identifiers
// ---------------------------------------------------------------------------

const IDENTIFIER_SHAPE = /^[A-Za-z_][A-Za-z0-9_]*$/;

/**
 * The one fixed list: reserved words of TypeScript (including strict-mode and
 * unbindable names) and of Java (keywords, literals and restricted
 * identifiers), so an identifier is safe to splice into either language.
 */
const RESERVED_WORDS: ReadonlySet<string> = new Set([
  // Shared by TypeScript and Java
  "break", "case", "catch", "class", "const", "continue", "default", "do", "else", "enum", "extends",
  "false", "finally", "for", "if", "implements", "import", "instanceof", "interface", "new", "null",
  "package", "private", "protected", "public", "return", "static", "super", "switch", "this", "throw",
  "true", "try", "void", "while",
  // TypeScript / JavaScript
  "arguments", "await", "debugger", "delete", "eval", "export", "function", "in", "let", "typeof",
  "undefined", "var", "with", "yield",
  // Java
  "_", "abstract", "assert", "boolean", "byte", "char", "double", "final", "float", "goto", "int",
  "long", "native", "permits", "record", "sealed", "short", "strictfp", "synchronized",
  "throws", "transient", "volatile",
]);

export const parseIdentifier: ParseIdentifierFn = (raw) => {
  if (!IDENTIFIER_SHAPE.test(raw)) return { ok: false, error: "invalid-identifier" };
  if (RESERVED_WORDS.has(raw)) return { ok: false, error: "reserved-word" };
  // The one place the brand is minted: the token passed both checks.
  return { ok: true, value: raw as Identifier };
};

export const parseContractId: ParseContractIdFn = (raw) =>
  // The one place the brand is minted: the token has the contract-id shape.
  CONTRACT_ID.test(raw) ? { ok: true, value: raw as ContractId } : { ok: false, error: "invalid-contract-id" };

// ---------------------------------------------------------------------------
// Grammar
// ---------------------------------------------------------------------------

const LABEL = /^\*\*Export bindings:\*\*/i;
const FENCE = /^\s*(```|~~~)/;
const ITEM_PATH = /^-\s+`([^`]*)`(.*)$/;
const SEPARATOR = /^[—–-]\s*(.*)$/;
/** A contract token, then optionally `: exports`; `parseContractId` decides the token. */
const QUALIFIED = /^([^:\s]+)(?:\s*:\s*(.*))?$/;

/** The lines a label owns: the label line itself (when it carries a value or
 *  no items follow) or its `- ` items. */
type LabelledLines =
  | Readonly<{ kind: "label-only"; line: string }>
  | Readonly<{ kind: "items"; items: NonEmpty<string> }>;

/** Every `**Export bindings:**` label outside a fence, with its items. */
function labelledLines(section: string): readonly LabelledLines[] {
  const lines = section.split("\n").map((line) => line.replace(/\r$/, "").trimEnd());
  const unfenced = fenceMask(lines);
  return lines.flatMap((line, at): LabelledLines[] => {
    if (!unfenced[at] || !LABEL.test(line)) return [];
    if (line.replace(LABEL, "").trim() !== "") return [{ kind: "label-only", line }];
    const after = lines.slice(at + 1);
    const firstItem = after.findIndex((candidate) => candidate.trim() !== "");
    const rest = firstItem === -1 ? [] : after.slice(firstItem);
    const end = rest.findIndex((candidate) => !candidate.startsWith("- "));
    const [first, ...others] = end === -1 ? rest : rest.slice(0, end);
    return first === undefined ? [{ kind: "label-only", line }] : [{ kind: "items", items: [first, ...others] }];
  });
}

/** Whether each line lies outside a fenced block; the marker that opened a
 *  fence is the only one that closes it. */
function fenceMask(lines: readonly string[]): readonly boolean[] {
  const mask: boolean[] = [];
  let open: string | null = null;
  for (const line of lines) {
    const marker = FENCE.exec(line)?.[1] ?? null;
    if (marker === null) {
      mask.push(open === null);
      continue;
    }
    mask.push(false);
    if (open === null) open = marker;
    else if (open === marker) open = null;
  }
  return mask;
}

/** One export entry (`name: Alias`), or why it is malformed. */
function parseEntry(raw: string): DomainResult<BoundExport, MalformedEntryReason> {
  const entry = raw.trim();
  if (entry === "") return { ok: false, error: "missing-name" };
  const colon = entry.indexOf(":");
  if (colon === -1) return { ok: false, error: "missing-alias" };
  const name = entry.slice(0, colon).trim();
  const alias = entry.slice(colon + 1).trim();
  if (name === "") return { ok: false, error: "missing-name" };
  if (alias === "") return { ok: false, error: "missing-alias" };
  const parsedName = parseIdentifier(name);
  if (!parsedName.ok) return parsedName;
  const parsedAlias = parseIdentifier(alias);
  if (!parsedAlias.ok) return parsedAlias;
  return { ok: true, value: { name: parsedName.value, alias: parsedAlias.value } };
}

/**
 * The export names of a binding at `path` that equal one of its aliases, in
 * first-appearance order — only where that collides: a TypeScript target
 * (`skeletonLanguageOf`, INV-6), whose skeleton imports every alias and
 * declares every name in one module scope (TS2440). A Java member and a type
 * may share a name, and an unsupported path gets no skeleton, so neither
 * collides. The plan grammar and the State File parser both refuse exactly these.
 */
export function aliasCollisions(path: string, exports: readonly BoundExport[]): readonly Identifier[] {
  const target = skeletonLanguageOf(path);
  if (target.kind !== "supported" || target.language !== "typescript") return [];
  const aliases = new Set<string>(exports.map(({ alias }) => alias));
  return [...new Set(exports.map(({ name }) => name).filter((name) => aliases.has(name)))];
}

/**
 * The aliases of a binding at `path` that equal the Java file's own class
 * name, in first-appearance order. The Java skeleton is `public final class
 * <FileBasename>` and imports each alias (`import pkg.Holder.Alias;`); an
 * alias of the class's own name clashes with that top-level declaration
 * (JLS 7.5.1). Only a Java target collides. The plan grammar and the State
 * File parser both refuse exactly these.
 */
export function aliasClassClashes(path: string, exports: readonly BoundExport[]): readonly Identifier[] {
  const target = skeletonLanguageOf(path);
  if (target.kind !== "supported" || target.language !== "java") return [];
  return [...new Set(exports.map(({ alias }) => alias).filter((alias) => alias === target.className))];
}

/** What one item line reads as. A line whose path and contract are readable
 *  counts toward its path's contracts even when its exports are malformed. */
type ItemReading =
  | Readonly<{ kind: "unreadable"; problems: NonEmpty<BindingProblem> }>
  | Readonly<{ kind: "read"; path: string; contract: ContractId; binding: ExportBinding | null; problems: readonly BindingProblem[] }>;

function readItem(line: string): ItemReading {
  const malformed = (path: string | null, reason: MalformedEntryReason): BindingProblem =>
    ({ kind: "malformed-entry", path, line, reason });
  const item = ITEM_PATH.exec(line);
  const rawPath = item?.[1]?.trim() ?? "";
  if (item === null || rawPath === "") return { kind: "unreadable", problems: [malformed(null, "not-a-binding-line")] };
  const path = normalizePlanPath(rawPath);
  const tail = item[2]!.trim();
  if (tail === "") return { kind: "unreadable", problems: [malformed(path, "missing-contract")] };
  const separated = SEPARATOR.exec(tail);
  if (separated === null) return { kind: "unreadable", problems: [malformed(path, "not-a-binding-line")] };
  const qualified = QUALIFIED.exec(separated[1]!.trim());
  const contractId = parseContractId(qualified?.[1] ?? "");
  if (qualified === null || !contractId.ok) return { kind: "unreadable", problems: [malformed(path, "missing-contract")] };
  const contract = contractId.value;
  const exportsText = (qualified[2] ?? "").trim();
  if (exportsText === "") return { kind: "read", path, contract, binding: null, problems: [malformed(path, "empty-exports")] };

  const entries = exportsText.split(",").map(parseEntry);
  const reasons = [...new Set(entries.flatMap((entry) => (entry.ok ? [] : [entry.error])))];
  const exports = entries.flatMap((entry) => (entry.ok ? [entry.value] : []));
  const names = exports.map(({ name }) => name);
  const duplicates = [...new Set(names.filter((name, index) => names.indexOf(name) !== index))];
  const collisions = aliasCollisions(path, exports);
  const classClashes = aliasClassClashes(path, exports);
  const problems: readonly BindingProblem[] = [
    ...reasons.map((reason) => malformed(path, reason)),
    ...duplicates.map((name): BindingProblem => ({ kind: "duplicate-name", path, name })),
    ...collisions.map((name): BindingProblem => ({ kind: "name-collides-with-alias", path, name })),
    ...classClashes.map((alias): BindingProblem => ({ kind: "alias-collides-with-class", path, alias })),
  ];
  const [first, ...rest] = exports;
  const binding = problems.length === 0 && first !== undefined ? { path, contract, exports: [first, ...rest] as const } : null;
  return { kind: "read", path, contract, binding, problems };
}

/** The path-level problems: a path on lines of two contracts, or on two lines of one. */
function pathProblems(readings: readonly Extract<ItemReading, { kind: "read" }>[]): ReadonlyMap<string, readonly BindingProblem[]> {
  const contractsByPath = new Map<string, ContractId[]>();
  for (const { path, contract } of readings) contractsByPath.set(path, [...(contractsByPath.get(path) ?? []), contract]);
  return new Map([...contractsByPath].map(([path, contracts]) => {
    const [first, second, ...others] = [...new Set(contracts)];
    const duplicated = [...new Set(contracts.filter((contract, index) => contracts.indexOf(contract) !== index))];
    const problems: readonly BindingProblem[] = [
      ...(second === undefined ? [] : [{ kind: "multi-contract", path, contracts: [first!, second, ...others] } as const]),
      ...duplicated.map((contract): BindingProblem => ({ kind: "duplicate-path", path, contract })),
    ];
    return [path, problems] as const;
  }));
}

export const parseExportBindings: ParseExportBindingsFn = (fileStructureSection): ExportBindingsDeclaration => {
  const labelled = labelledLines(fileStructureSection);
  const lineProblems: BindingProblem[] = [];
  const readings: Extract<ItemReading, { kind: "read" }>[] = [];
  for (const entry of labelled) {
    if (entry.kind === "label-only") {
      lineProblems.push({ kind: "malformed-entry", path: null, line: entry.line, reason: "not-a-binding-line" });
      continue;
    }
    for (const line of entry.items) {
      const reading = readItem(line);
      lineProblems.push(...reading.problems);
      if (reading.kind === "read") readings.push(reading);
    }
  }
  const byPath = pathProblems(readings);
  const bindings = readings.flatMap(({ path, binding }) =>
    binding !== null && (byPath.get(path) ?? []).length === 0 ? [binding] : []);
  return { bindings, problems: [...lineProblems, ...[...byPath.values()].flat()] };
};

/** One binding as the canonical `**Export bindings:**` item line; parsing it
 *  back yields the binding. */
export function renderExportBinding(binding: ExportBinding): string {
  return `- \`${binding.path}\` — ${binding.contract}: ${binding.exports.map(({ name, alias }) => `${name}: ${alias}`).join(", ")}`;
}

