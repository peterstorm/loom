/**
 * The plan grammar for `**Export bindings:**` (AD-3), the one `Identifier`
 * and `ContractId` constructors, and binding validation (FR-002).
 *
 * In `## File Structure`, outside any fence, the column-0 `**Export
 * bindings:**` label is followed by `- ` items (blank lines before the first
 * item allowed, the list ending at the first line that is not an item — the
 * `labelledList` grammar of the plan parser, applied to the Export bindings
 * label only; no other label of the section is read here):
 *
 *     **Export bindings:**
 *     - `src/order/pricing.ts` — CT-1: priceOrder: PriceOrderFn, parseOrder: ParseOrderFn
 *
 * One contract per line: a path on lines of two contracts is `multi-contract`,
 * on two lines of one contract `duplicate-path`. Every name and alias is
 * minted by `parseIdentifier`, so generated bytes only ever splice validated
 * identifiers, and every contract by `parseContractId`. On a TypeScript
 * binding, a name equal to an alias of its own line is
 * `name-collides-with-alias`: the TypeScript skeleton would import that alias
 * and declare the name in one scope. A Java binding may reuse an alias as a
 * name — a Java field and a type never share a namespace — but no alias may
 * be the file's own class name (`alias-collides-with-class`): the skeleton
 * imports every alias, and that import would clash with the class itself.
 *
 * Pure and total: every problem is collected as a `BindingProblem`, never thrown.
 */

